// 보도사의 순서 번호 (작을수록 먼저 뽑힌다. 목록에 없으면 단계 뒤, 본문을 못 가져오는 곳은 맨 뒤)
export function sourceRank(source: string): number {
  if (BODY_UNAVAILABLE_SOURCES.includes(source)) return SOURCE_TIERS.length + 1;
  const index = SOURCE_TIERS.findIndex((tier) => tier.includes(source));
  return index === -1 ? SOURCE_TIERS.length : index;
}

